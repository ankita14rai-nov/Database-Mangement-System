-- Find duplicate records.
WITH DuplicateRecords AS
(
SELECT ID, NAME, CITY, DEPARTMENT, SALARY, ROW_NUMBER()
OVER(PARTITION BY NAME, CITY, DEPARTMENT, SALARY
ORDER BY ID) AS DUP_RECORD FROM EMP 
)

SELECT * FROM DuplicateRecords
WHERE DUP_RECORD > 1;



-- DELETE the duplicate records
WITH DuplicateRecords AS
(
SELECT ID, NAME, CITY, DEPARTMENT, SALARY, ROW_NUMBER()
OVER(PARTITION BY NAME, CITY, DEPARTMENT, SALARY
ORDER BY ID) AS DUP_RECORD FROM EMP 
)

DELETE FROM DuplicateRecords
WHERE DUP_RECORD > 1;

