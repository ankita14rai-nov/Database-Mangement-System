-- RANK vs DENSE_RANK vs ROW_NUMBER
SELECT
    NAME,
    SALARY,

    ROW_NUMBER() OVER
    (
        ORDER BY SALARY DESC
    ) AS ROW_NUM,

    RANK() OVER
    (
        ORDER BY SALARY DESC
    ) AS RNK,

    DENSE_RANK() OVER
    (
        ORDER BY SALARY DESC
    ) AS DENSE_RNK

FROM EMP;


